#!/usr/bin/env node
// Generates a Maestro smoke flow for each demo in the manifest (one per
// component in Atoms/Molecules/Organisms/Examples). Without generating them,
// adding a new component doesn't add coverage on its own — the same reason
// gen-exports.mjs derives package.json's "exports" map from src/ instead of
// maintaining it by hand.
//
// Manifest parsing lives in scripts/manifest-parse.mjs, shared with
// gen-maestro-demos.mjs (the docs clips): they are the same manifests read as
// text, and having two parsers was a guarantee they'd drift apart.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseAllManifests } from './manifest-parse.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const FLOWS_DIR = path.join(ROOT, '.maestro/flows/smoke');
const APP_ID = 'com.anonymous.orn-ui-example';

// The only hand-written flows in flows/smoke/ (they don't derive from a
// manifest entry) — excluded from the "leftovers" cleanup so gen:maestro
// doesn't delete them. See README: nav-tabs-and-list.yaml is the only one that
// navigates tabs/list/back instead of entering via deep link.
const HAND_WRITTEN = new Set(['nav-tabs-and-list.yaml']);

function yamlEscape(text) {
  return text.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function flowFor(entry) {
  return `# Generated by scripts/gen-maestro-flows.mjs — do not edit by hand.
# Source: ${entry.basePath === 'examples' ? 'demos/examples/manifest.ts' : 'demos/manifest.ts'} (slug: ${entry.slug})
appId: ${APP_ID}
tags:
  - smoke
---
- runFlow:
    file: ../../subflows/smoke-demo.yaml
    env:
      MAESTRO_APP_ID: ${APP_ID}
      BASE_PATH: "${entry.basePath}"
      SLUG: "${entry.slug}"
      TITLE: "${yamlEscape(entry.name)}"
      PAGED: "${entry.paged}"
`;
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const entries = parseAllManifests(ROOT);

  const seen = new Set();
  for (const entry of entries) {
    const key = `${entry.basePath}/${entry.slug}`;
    if (seen.has(key)) throw new Error(`Duplicate slug: ${key}`);
    seen.add(key);
  }

  fs.mkdirSync(FLOWS_DIR, { recursive: true });
  const wanted = new Map(entries.map((e) => [`${e.basePath}-${e.slug}.yaml`, flowFor(e)]));

  const existing = fs.existsSync(FLOWS_DIR) ? fs.readdirSync(FLOWS_DIR) : [];
  const stale = existing.filter((f) => f.endsWith('.yaml') && !wanted.has(f) && !HAND_WRITTEN.has(f));

  let changed = false;
  for (const [filename, content] of wanted) {
    const filePath = path.join(FLOWS_DIR, filename);
    // Windows checkout puede dejar CRLF; el contenido generado es siempre LF.
    const current = fs.existsSync(filePath)
      ? fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n')
      : null;
    if (current !== content) {
      changed = true;
      if (checkOnly) {
        console.error(`✗ out of date: .maestro/flows/smoke/${filename}`);
      } else {
        fs.writeFileSync(filePath, content);
      }
    }
  }
  for (const filename of stale) {
    changed = true;
    if (checkOnly) {
      console.error(`✗ leftover: .maestro/flows/smoke/${filename}`);
    } else {
      fs.unlinkSync(path.join(FLOWS_DIR, filename));
    }
  }

  if (checkOnly) {
    if (changed) {
      console.error(`\nThe Maestro smoke flows are out of date. Run: pnpm --filter example gen:maestro`);
      process.exit(1);
    }
    console.log(`✓ ${entries.length} smoke flows up to date`);
    return;
  }

  console.log(`✓ Generated ${entries.length} smoke flows in .maestro/flows/smoke/`);
}

main();
